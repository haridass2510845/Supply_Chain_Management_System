-- ============================================================
-- Module 4 (Warehouse Management)
-- WH-01 Receive Goods, WH-02 Store Inventory, WH-03 Update Stock,
-- WH-04 Dispatch Goods, WH-05 Warehouse Reports
-- ============================================================

CREATE TABLE inventory (
    item_id           NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    item_name         VARCHAR2(150) NOT NULL UNIQUE,
    quantity_on_hand  NUMBER(12) DEFAULT 0 NOT NULL,
    reorder_level     NUMBER(12) DEFAULT 0 NOT NULL,
    location          VARCHAR2(100),
    updated_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE inventory_transactions (
    txn_id        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    item_id       NUMBER NOT NULL REFERENCES inventory(item_id),
    po_id         NUMBER REFERENCES purchase_orders(po_id),
    txn_type      VARCHAR2(20) NOT NULL
                  CONSTRAINT chk_txn_type CHECK (txn_type IN ('RECEIVE','DISPATCH','ADJUSTMENT')),
    quantity      NUMBER(12) NOT NULL,
    performed_by  VARCHAR2(50),
    remarks       VARCHAR2(255),
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

