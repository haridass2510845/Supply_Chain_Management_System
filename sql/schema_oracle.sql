-- ============================================================
-- Module 3 (Procurement Management) - Purchase Orders
-- PO-01 Create, PO-02 Approve, PO-03 Cancel, PO-04 Track Status,
-- PO-05 Supplier Performance, PO-06 Reports
-- ============================================================

CREATE TABLE purchase_orders (
    po_id          NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    supplier_id    NUMBER NOT NULL REFERENCES suppliers(supplier_id),
    item_name      VARCHAR2(150) NOT NULL,
    quantity       NUMBER(10)     NOT NULL,
    unit_price     NUMBER(12,2)   NOT NULL,
    total_amount   NUMBER(14,2)   NOT NULL,
    status         VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
                   CONSTRAINT chk_po_status
                   CHECK (status IN ('PENDING','APPROVED','SHIPPED','CANCELLED','COMPLETED')),
    created_by     VARCHAR2(50),
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    approved_by    VARCHAR2(50),
    approved_at    TIMESTAMP,
    shipped_at     TIMESTAMP,
    delivered_at   TIMESTAMP,
    remarks        VARCHAR2(255)
);

